/**
 * Points the app at the build's brand files.
 *
 * A client build keeps everything it owns in `brand/` (which this repository never
 * ships), so pulling a new release never touches a client file:
 *
 *   brand/navigator.brand.ts         branding (colours, schemes, type, tabs, features, …)
 *   brand/navigator.extensions.ts    screen and component overrides, custom routes and tabs
 *   brand/translations/<locale>.json  copy added to or replacing the app's strings
 *   brand/fonts/*.ttf|otf             font files named by their PostScript name
 *   brand/logo.png                    the sign-in logo (optional)
 *   brand/app-icon.png                1024×1024 app icon (scripts/generate-app-assets.js)
 *   brand/splash-screen.png           launch screen artwork (scripts/generate-app-assets.js)
 *
 * Each one is optional. Missing files fall back to the templates at the repository
 * root (navigator.brand.ts, navigator.extensions.ts) or to nothing.
 *
 * The result is written to src/v3/generated (git-ignored) as plain modules so every
 * tool resolves it the same way: Metro, Jest and tsc. It runs from babel.config.js,
 * metro.config.js, postinstall and typecheck, and only rewrites a file whose content
 * changed so watchers don't loop.
 */
const fs = require('fs');
const path = require('path');

const FONT_EXTENSIONS = ['.ttf', '.otf'];
const HEADER = '// Generated by scripts/link-brand.js from brand/ (or the root templates). Do not edit.\n';

function writeIfChanged(file, content) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === content) return false;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    return true;
}

const exists = (file) => fs.existsSync(file);
const firstExisting = (root, candidates) => candidates.find((candidate) => ['.ts', '.tsx', '.js'].some((ext) => exists(path.join(root, candidate + ext))));

function linkBrand(root = path.resolve(__dirname, '..')) {
    const brandDir = path.join(root, 'brand');
    const outDir = path.join(root, 'src', 'v3', 'generated');
    const rel = (target) => {
        const relative = path.relative(outDir, path.join(root, target)).split(path.sep).join('/');
        return relative.startsWith('.') ? relative : `./${relative}`;
    };

    const brandConfig = firstExisting(root, ['brand/navigator.brand', 'navigator.brand']);
    const brandExtensions = firstExisting(root, ['brand/navigator.extensions', 'navigator.extensions']);
    const usesBrandDir = [brandConfig, brandExtensions].some((file) => file && file.startsWith('brand/'));

    writeIfChanged(
        path.join(outDir, 'brand-config.ts'),
        `${HEADER}import brandConfig from '${rel(brandConfig)}';\n\nexport const BRAND_DIR = ${usesBrandDir ? "'brand'" : 'null'};\nexport default brandConfig;\n`
    );
    writeIfChanged(path.join(outDir, 'brand-extensions.ts'), `${HEADER}import brandExtensions from '${rel(brandExtensions)}';\n\nexport default brandExtensions;\n`);

    // Translations: brand/translations/<locale>.json
    const translationsDir = path.join(brandDir, 'translations');
    const locales = exists(translationsDir)
        ? fs
              .readdirSync(translationsDir)
              .filter((file) => file.endsWith('.json'))
              .map((file) => file.replace(/\.json$/, ''))
              .filter((locale) => /^[a-zA-Z]{2,3}([_-][a-zA-Z0-9]{2,8})?$/.test(locale))
              .sort()
        : [];
    const translationImports = locales.map((locale, index) => `import t${index} from '${rel(`brand/translations/${locale}.json`)}';`).join('\n');
    const translationMap = locales.map((locale, index) => `    ${JSON.stringify(locale)}: t${index},`).join('\n');
    writeIfChanged(
        path.join(outDir, 'brand-translations.ts'),
        `${HEADER}${translationImports}${translationImports ? '\n\n' : ''}const brandTranslations: Record<string, Record<string, any>> = {\n${translationMap}${translationMap ? '\n' : ''}};\n\nexport default brandTranslations;\n`
    );

    // Fonts: brand/fonts/<PostScriptName>.<ext>. Native builds link the folder
    // (react-native.config.js); the list lets branding check a face exists.
    const fontsDir = path.join(brandDir, 'fonts');
    const fonts = exists(fontsDir)
        ? fs
              .readdirSync(fontsDir)
              .filter((file) => FONT_EXTENSIONS.includes(path.extname(file).toLowerCase()))
              .map((file) => path.basename(file, path.extname(file)))
              .sort()
        : [];

    // The sign-in logo: brand/logo.png and, for the dark schemes, brand/logo-dark.png.
    const logo = exists(path.join(brandDir, 'logo.png')) ? 'brand/logo.png' : null;
    const logoDark = exists(path.join(brandDir, 'logo-dark.png')) ? 'brand/logo-dark.png' : null;
    writeIfChanged(
        path.join(outDir, 'brand-assets.ts'),
        `${HEADER}/** Font files bundled from brand/fonts, by PostScript name. */\nexport const brandFonts: string[] = ${JSON.stringify(fonts)};\n\n` +
            `/** The sign-in logo (brand/logo.png), and its dark-scheme variant (brand/logo-dark.png). */\n` +
            `export const logo: number | null = ${logo ? `require('${rel(logo)}')` : 'null'};\n` +
            `export const logoDark: number | null = ${logoDark ? `require('${rel(logoDark)}')` : 'null'};\n`
    );

    return { brandConfig, brandExtensions, locales, fonts, logo: Boolean(logo) };
}

module.exports = { linkBrand };

if (require.main === module) {
    const result = linkBrand();
    console.log(
        `[link-brand] branding: ${result.brandConfig}, extensions: ${result.brandExtensions}, translations: ${result.locales.join(', ') || 'none'}, fonts: ${result.fonts.length}, logo: ${result.logo ? 'yes' : 'no'}`
    );
}
